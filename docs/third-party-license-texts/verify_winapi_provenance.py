#!/usr/bin/env python3
"""Compare pinned published winapi 0.4.0 files with immutable upstream Git blobs.

Only reads a saved Cargo metadata document, the extracted registry sources named
there, and public GitHub tree responses. It does not invoke Cargo or modify the
registry. Exit nonzero if either package, an upstream file, or any byte differs.
"""
import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path
import urllib.request

COMMIT = '9497609ef44cc9bcd16cd2411c0ee6ccaf5483aa'
REPOSITORY = 'https://github.com/retep998/winapi-rs'
TREE_BASE = 'https://api.github.com/repos/retep998/winapi-rs/git/trees/'
PACKAGES = {
    'winapi-i686-pc-windows-gnu': 'i686',
    'winapi-x86_64-pc-windows-gnu': 'x86_64',
}


def fetch_tree(reference, recursive=False):
    url = TREE_BASE + reference + ('?recursive=1' if recursive else '')
    request = urllib.request.Request(url, headers={
        'User-Agent': 'Vela-local-license-provenance-verification',
        'Accept': 'application/vnd.github+json',
    })
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read(5 * 1024 * 1024 + 1)
    if len(data) > 5 * 1024 * 1024:
        raise RuntimeError('GitHub tree response exceeded the bounded read limit')
    tree = json.loads(data)
    if tree.get('truncated'):
        raise RuntimeError('Truncated GitHub tree cannot establish file provenance')
    return tree


def verify(package, subtree_sha):
    folder = PACKAGES[package['name']]
    tree = fetch_tree(subtree_sha, recursive=True)
    entries = {entry['path']: entry for entry in tree['tree'] if entry['type'] == 'blob'}
    root = Path(package['manifest_path']).parent
    mismatches = []
    unmatched = []
    compared = 0
    compared_bytes = 0
    for path in sorted(root.rglob('*')):
        if not path.is_file():
            continue
        if path.is_symlink():
            raise RuntimeError('Unexpected symlink in extracted registry source')
        relative = path.relative_to(root).as_posix()
        # These two files are generated by Cargo, not authored upstream.
        if relative in ('Cargo.toml', '.cargo-ok'):
            continue
        if relative == 'Cargo.toml.orig':
            relative = 'Cargo.toml'
        expected = entries.get(relative)
        if expected is None:
            unmatched.append(relative)
            continue
        data = path.read_bytes()
        # Git blob identity includes its object header, not just file bytes.
        blob_sha = hashlib.sha1(b'blob ' + str(len(data)).encode('ascii') + b'\0' + data).hexdigest()
        compared += 1
        compared_bytes += len(data)
        if blob_sha != expected['sha']:
            mismatches.append({
                'path': relative,
                'upstream_blob': expected['sha'],
                'local_blob': blob_sha,
            })
    return {
        'package': package['name'],
        'version': package['version'],
        'repository': REPOSITORY,
        'commit': COMMIT,
        'subdirectory': folder,
        'subtree_sha': subtree_sha,
        'truncated': tree.get('truncated', False),
        'files_compared': compared,
        'bytes_compared': compared_bytes,
        'mismatches': mismatches,
        'unmatched': unmatched,
        'source_tree_url': TREE_BASE + subtree_sha + '?recursive=1',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--metadata', type=Path, default=Path('target/checks/jobs-cargo-metadata.json'))
    args = parser.parse_args()
    metadata = json.loads(args.metadata.read_text())
    packages = [package for package in metadata['packages']
                if package['name'] in PACKAGES and package['version'] == '0.4.0']
    if len(packages) != 2 or {package['name'] for package in packages} != set(PACKAGES):
        raise RuntimeError('Expected exactly both pinned winapi platform packages at 0.4.0')
    upstream_root = fetch_tree(COMMIT)
    folders = {entry['path']: entry['sha'] for entry in upstream_root['tree'] if entry['type'] == 'tree'}
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as executor:
        results = list(executor.map(
            lambda package: verify(package, folders[PACKAGES[package['name']]]), packages))
    print(json.dumps(results, indent=2))
    if any(result['mismatches'] or result['unmatched'] or result['files_compared'] == 0
           for result in results):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
